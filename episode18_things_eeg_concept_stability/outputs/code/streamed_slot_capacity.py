"""Inactive exact capacity backend for the existing EP18 sequence operators.

This module reads no files, EEG or scores and selects no model or recipe. It
emits one physical-sequence row block and factors one added slot at a time.
The caller supplies the original designs/weights/penalties, rank tolerance,
row/block sizes, array allowance and an allocation/deadline/RSS callback.

For A0=[sqrt(W) X0; sqrt(P0)], streaming triangular QR followed by a complete
SVD of R gives the same base coefficient range as the dense implementation.
With D=V_ret/s_ret, U_data=sqrt(W) X0 D and C=U_data' sqrt(W) Xa, the slot
root is F=[sqrt(W) Xa-U_data C; sqrt(P0) D C]. Its QR/SVD never forms a
normal Gram matrix. Every original slot singular direction is retained;
only the base uses the caller's original relative cutoff. Added-term EDF is
sum(s^2/(s^2+lambda)); incremental EDF uses ||E v||^2 instead. Selected joint
leverages include the base refit, exactly as slot_capacity._evaluate_slot.

DTPQRT(L=0) updates the triangular factor without a full Q. DGESVD uses the
explicit minimum square-matrix workspace (5*width), not a divide-and-conquer
workspace or an implicit full-Q allocation. Fortran-contiguous owned buffers
permit overwrite. LAPACK INFO failures stop; there is no alternate algorithm,
rank relaxation, clipping, stochastic trace or automatic retry.

The allowance covers this backend's arrays, including retained results. The
existing caller-owned operators/features/EEG and BLAS thread-private native
buffers are outside it and require the actual process/Slurm cap. Work remains
O(n*p^2 + n*p*q + n*q^2 + p^3 + q^3) per base/slot; small-memory execution is
not a full-scale speed or completion claim. No fitter/controller is changed.

Reference interfaces:
https://docs.scipy.org/doc/scipy/reference/generated/scipy.linalg.lapack.dtpqrt.html
https://docs.scipy.org/doc/scipy/reference/generated/scipy.linalg.lapack.dgesvd.html
"""
from __future__ import annotations

from dataclasses import dataclass, field
from numbers import Integral, Real
from types import MappingProxyType

import numpy as np
from scipy.linalg import lapack

from continuous_sequence_model import JointSequenceDesign
from slot_capacity import RIDGE_GRID, SlotCapacityCurve, SlotCapacityResult


def _integer(value, name, *, zero=False):
    if (isinstance(value, (bool, np.bool_)) or not isinstance(value, Integral)
            or value < (0 if zero else 1)):
        raise ValueError(name + " must be an explicit bounded integer")
    return int(value)


def _frozen(value):
    value.setflags(write=False)
    return value


def _indices(values):
    result = tuple(values)
    if (len(result) != len(set(result)) or any(isinstance(i, (bool, np.bool_))
            or not isinstance(i, Integral) or not 0 <= i < 13 for i in result)):
        raise ValueError("Selected leverages require distinct original penalty indices")
    return tuple(map(int, result))


def _finite_blocks(value, chunk, check):
    # Avoid a q-by-q Boolean temporary while checking the square SVD output.
    for start in range(0, len(value), chunk):
        check()
        if not np.isfinite(value[start:start + chunk]).all():
            raise ArithmeticError("Nonfinite exact factor or emitted design")


@dataclass(frozen=True)
class SequenceRows:
    """An explicit contiguous column view of an existing complete operator.

    A view retains the original operator; it does not copy its kernels or
    expose samples from another physical sequence. No column is generated by
    applying the entire operator to a unit coefficient vector.
    """
    design: JointSequenceDesign = field(repr=False, compare=False)
    start_column: int
    stop_column: int

    def __post_init__(self):
        if not isinstance(self.design, JointSequenceDesign):
            raise TypeError("An existing JointSequenceDesign is required")
        start = _integer(self.start_column, "column start", zero=True)
        stop = _integer(self.stop_column, "column stop", zero=True)
        if not 0 <= start <= stop <= self.design.shape[1]:
            raise ValueError("Column view is outside its original operator")

    @property
    def rows(self):
        return self.design.shape[0]

    @property
    def columns(self):
        return self.stop_column - self.start_column

    def blocks(self, *, chunk_rows, budget_check):
        chunk = _integer(chunk_rows, "row block size")
        if not callable(budget_check):
            raise TypeError("An explicit budget callback is required")
        offset = 0
        for sequence in self.design.sequences:
            for first in range(0, sequence.shape[0], chunk):
                budget_check()
                last = min(sequence.shape[0], first + chunk)
                result = np.zeros((last - first, self.columns), dtype=np.float64, order="F")
                lo, hi = self.start_column, min(self.stop_column, sequence.nuisance.shape[1])
                if hi > lo:
                    result[:, :hi - lo] = sequence.nuisance[first:last, lo:hi]
                for term in sequence.terms.values():
                    lower = max(self.start_column, term.column_slice.start)
                    upper = min(self.stop_column, term.column_slice.stop)
                    if upper <= lower:
                        continue
                    width = term.basis_dimension
                    local_lower, local_upper = lower - term.column_slice.start, upper - term.column_slice.start
                    for event, (event_start, event_stop, kernel) in enumerate(term.kernels):
                        a, b = max(first, event_start), min(last, event_stop)
                        if b <= a:
                            continue
                        budget_check()
                        # One-hot slots touch only their actual group's columns;
                        # continuous image/label terms retain every nonzero value.
                        active = np.flatnonzero(term.features[event])
                        active = active[(active >= local_lower // width)
                                        & (active <= (local_upper - 1) // width)]
                        columns = (active[:, None] * width + np.arange(width)).reshape(-1)
                        columns = columns[(columns >= local_lower) & (columns < local_upper)]
                        if not len(columns):
                            continue
                        contribution = (kernel[a - event_start:b - event_start, columns % width]
                                        * term.features[event, columns // width])
                        destination = term.column_slice.start + columns - self.start_column
                        result[a - first:b - first, destination] += contribution
                _finite_blocks(result, chunk, budget_check)
                yield offset + first, offset + last, result
            offset += sequence.shape[0]
        if offset != self.rows:
            raise ValueError("Physical sequence row coverage differs from the operator")


def _same_rows_and_base(base, added):
    if not isinstance(base, SequenceRows) or not isinstance(added, SequenceRows):
        raise TypeError("Use explicit existing-operator column views")
    if (base.start_column != 0 or base.rows != added.rows
            or added.start_column != base.stop_column
            or added.stop_column != added.design.shape[1]
            or len(base.design.sequences) != len(added.design.sequences)):
        raise ValueError("Slot must append to the same complete base and row axis")
    for left, right in zip(base.design.sequences, added.design.sequences):
        if (left.sequence_id != right.sequence_id or left.shape[0] != right.shape[0]
                or not np.array_equal(left.sample_times, right.sample_times)
                or not np.array_equal(left.nuisance, right.nuisance)):
            raise ValueError("Base/slot physical clocks or nuisance differ")
        # The base may itself be a prefix view of the same expanded operator.
        for name, term in left.terms.items():
            if term.column_slice.stop > base.stop_column:
                if term.column_slice.start < base.stop_column:
                    raise ValueError("A shared base cannot cut through a named term")
                continue
            other = right.terms.get(name)
            if (other is None or term.column_slice != other.column_slice
                    or term.basis_dimension != other.basis_dimension
                    or not np.array_equal(term.features, other.features)
                    or len(term.kernels) != len(other.kernels)
                    or any(a[:2] != b[:2] or not np.array_equal(a[2], b[2])
                           for a, b in zip(term.kernels, other.kernels))):
                raise ValueError("Added slot changed the shared time-expanded base")
        if any(term.column_slice.start < base.stop_column and name not in left.terms
               for name, term in right.terms.items()):
            raise ValueError("Added slot introduced a different base term")


def estimate_array_bytes(*, rows, base_columns, slot_columns, chunk_rows,
                         qr_block_size, retained_leverage_vectors):
    """Conservative explicit-array bound; external source/BLAS buffers excluded.

    p^2 is the base right factor; p*q is the shared projection; q^2 is the
    triangular/SVD factor. No n*p or n*q matrix is retained. The estimates
    reserve row-emission/products/finite checks and Python spectrum tuples.
    """
    n = _integer(rows, "rows")
    p = _integer(base_columns, "base columns", zero=True)
    q = _integer(slot_columns, "slot columns", zero=True)
    b = min(n, _integer(chunk_rows, "row block size"))
    k = _integer(qr_block_size, "QR block size")
    h = _integer(retained_leverage_vectors, "retained leverage vectors", zero=True)
    base = 8 * (4*p*p + 12*b*p + 4*k*p + (20+h)*n + 64*p)
    slot = 8 * (2*p*p + 2*p*q + 3*q*q + 12*b*(p+q)
                + 4*k*(p+q) + (20+h)*n + 64*(p+q))
    return {"base_peak_array_bytes": base, "slot_peak_array_bytes": slot,
            "required_array_bytes": max(base, slot),
            "caller_operator_and_BLAS_private_buffers_included": False}


class _TriangularQR:
    def __init__(self, columns, *, qr_block_size, chunk_rows, check):
        self.columns, self.block, self.chunk, self.check = columns, qr_block_size, chunk_rows, check
        self.factor = np.zeros((columns, columns), dtype=np.float64, order="F")

    def append(self, block):
        self.check()
        if block.shape[1] != self.columns or len(block) > self.chunk:
            raise ValueError("QR append exceeds the selected row/column bounds")
        if not self.columns or not len(block):
            return
        # L=0: the lower block is rectangular. A is the accumulated upper R.
        # No Q, stacked (q+b)-by-q copy or q-by-q normal Gram is formed.
        owned = np.array(block, dtype=np.float64, copy=True, order="F")
        result, overwritten, reflectors, info = lapack.dtpqrt(
            0, min(self.block, self.columns), self.factor, owned,
            overwrite_a=1, overwrite_b=1)
        if info != 0:
            raise ArithmeticError("Triangular row-block QR did not complete")
        self.factor = result
        del owned, overwritten, reflectors
        self.check()

    def svd(self):
        self.check()
        if not self.columns:
            self.factor = None
            return np.empty(0), np.empty((0, 0))
        left, singular, right, info = lapack.dgesvd(self.factor, compute_uv=1,
            full_matrices=0, lwork=max(1, 5*self.columns), overwrite_a=1)
        self.factor = None
        del left
        if info != 0 or not np.isfinite(singular).all():
            raise ArithmeticError("Complete triangular SVD did not converge")
        _finite_blocks(right, self.chunk, self.check)
        self.check()
        return singular, right


@dataclass(frozen=True)
class StreamedBase:
    source: SequenceRows = field(repr=False, compare=False)
    root_weights: np.ndarray = field(repr=False, compare=False)
    root_penalties: np.ndarray = field(repr=False, compare=False)
    right_scaled: np.ndarray = field(repr=False, compare=False)
    base_leverage: np.ndarray = field(repr=False, compare=False)
    singular_values: tuple[float, ...]
    numerical_rank: int
    rank_relative_tolerance: float
    rank_threshold: float
    model_edf: float
    chunk_rows: int
    qr_block_size: int
    array_byte_cap: int
    retained_leverage_vectors: int
    check: object = field(repr=False, compare=False)


def prepare_streamed_base(*, base_design, sample_weights, base_penalties,
                          base_rank_relative_tolerance, chunk_rows, qr_block_size,
                          array_byte_cap, retained_leverage_vectors, budget_check):
    if not isinstance(base_design, SequenceRows) or base_design.start_column != 0:
        raise TypeError("An explicit base-prefix SequenceRows is required")
    if not callable(budget_check):
        raise TypeError("An explicit allocation/deadline callback is required")
    chunk = _integer(chunk_rows, "row block size")
    qr_block = _integer(qr_block_size, "QR block size")
    cap = _integer(array_byte_cap, "array byte cap")
    count = _integer(retained_leverage_vectors, "retained leverage vectors", zero=True)
    p, n = base_design.columns, base_design.rows
    estimate = estimate_array_bytes(rows=n, base_columns=p, slot_columns=0,
        chunk_rows=chunk, qr_block_size=qr_block, retained_leverage_vectors=count)
    if estimate["required_array_bytes"] > cap:
        raise MemoryError("Streamed base exceeds the explicit array allowance")
    tolerance = base_rank_relative_tolerance
    if (isinstance(tolerance, (bool, np.bool_)) or not isinstance(tolerance, Real)
            or not np.isfinite(tolerance) or not 0 <= tolerance < 1):
        raise ValueError("Preserve the explicit base relative SVD cutoff")
    weights, penalties = np.asarray(sample_weights), np.asarray(base_penalties)
    if (weights.dtype.kind not in "fiu" or weights.shape != (n,)
            or penalties.dtype.kind not in "fiu" or penalties.shape != (p,)
            or not np.isfinite(weights).all() or not np.isfinite(penalties).all()
            or np.any(weights < 0) or np.any(penalties < 0) or not np.any(weights > 0)):
        raise ValueError("Original finite nonnegative weights/penalties are required")
    budget_check()
    with np.errstate(over="raise", invalid="raise", divide="raise"):
        root = _frozen(np.sqrt(weights.astype(np.float64)))
        penalty_root = _frozen(np.sqrt(penalties.astype(np.float64)))
    accumulator = _TriangularQR(p, qr_block_size=qr_block, chunk_rows=chunk, check=budget_check)
    for first, last, block in base_design.blocks(chunk_rows=chunk, budget_check=budget_check):
        with np.errstate(over="raise", invalid="raise"):
            block *= root[first:last, None]
        accumulator.append(block)
    for first in range(0, p, chunk):
        last = min(p, first+chunk)
        block = np.zeros((last-first, p), dtype=np.float64, order="F")
        block[np.arange(last-first), np.arange(first, last)] = penalty_root[first:last]
        accumulator.append(block)
    singular, right = accumulator.svd()
    threshold = float(tolerance * singular[0]) if p else 0.
    retained = singular > threshold
    scaled = np.array(right[retained].T, dtype=np.float64, copy=True, order="F")
    if scaled.shape[1]:
        with np.errstate(over="raise", invalid="raise", divide="raise"):
            scaled /= singular[retained]
    del right
    _finite_blocks(scaled, chunk, budget_check)
    leverage = np.empty(n)
    for first, last, block in base_design.blocks(chunk_rows=chunk, budget_check=budget_check):
        with np.errstate(over="raise", invalid="raise"):
            block *= root[first:last, None]
            left = block @ scaled
            leverage[first:last] = np.sum(left*left, axis=1)
    if not np.isfinite(leverage).all():
        raise ArithmeticError("Nonfinite streamed base influence")
    budget_check()
    return StreamedBase(base_design, root, penalty_root, _frozen(scaled), _frozen(leverage),
        tuple(map(float, singular)), int(np.count_nonzero(retained)), float(tolerance), threshold,
        float(np.sum(leverage)), chunk, qr_block, cap, count, budget_check)


def _paired_blocks(base, slot):
    first_source = base.source.blocks(chunk_rows=base.chunk_rows, budget_check=base.check)
    second_source = slot.blocks(chunk_rows=base.chunk_rows, budget_check=base.check)
    completed = 0
    # Both concrete sources preserve the previously checked sequence boundaries.
    for first, second in zip(first_source, second_source, strict=True):
        if first[:2] != second[:2] or first[0] != completed:
            raise ValueError("Base and slot row blocks are not exactly aligned")
        lo, hi, base_block = first
        slot_block = second[2]
        root = base.root_weights[lo:hi, None]
        base_block *= root
        slot_block *= root
        left = base_block @ base.right_scaled
        yield lo, hi, left, slot_block
        completed = hi
    if completed != base.source.rows:
        raise ValueError("Incomplete weighted physical-sequence coverage")


@dataclass(frozen=True)
class StreamedSlot:
    curve: SlotCapacityCurve
    joint_leverages: object = field(repr=False, compare=False)
    array_admission_bytes: int

    @property
    def design_singular_values(self):
        # Match selected_design_diagnostics: append only structural zero directions.
        values = self.curve.schur_singular_values
        return values + (0.,) * (self.curve.slot_columns - len(values))


def evaluate_streamed_slot(base, *, slot_name, slot_design, leverage_penalty_indices):
    if not isinstance(base, StreamedBase) or not isinstance(slot_name, str) or not slot_name:
        raise TypeError("A prepared streamed base and named slot are required")
    _same_rows_and_base(base.source, slot_design)
    indices = _indices(leverage_penalty_indices)
    if len(indices) > base.retained_leverage_vectors:
        raise ValueError("Selected leverages must use distinct admitted original penalty indices")
    p, n, q = base.source.columns, base.source.rows, slot_design.columns
    estimate = estimate_array_bytes(rows=n, base_columns=p, slot_columns=q,
        chunk_rows=base.chunk_rows, qr_block_size=base.qr_block_size,
        retained_leverage_vectors=base.retained_leverage_vectors)
    if estimate["required_array_bytes"] > base.array_byte_cap:
        raise MemoryError("Exact streamed slot exceeds the explicit array allowance")
    base.check()
    coordinates = np.zeros((base.numerical_rank, q), dtype=np.float64, order="F")
    with np.errstate(over="raise", invalid="raise", divide="raise"):
        for _, _, left, slot in _paired_blocks(base, slot_design):
            coordinates += left.T @ slot
        accumulator = _TriangularQR(q, qr_block_size=base.qr_block_size,
            chunk_rows=base.chunk_rows, check=base.check)
        for _, _, left, slot in _paired_blocks(base, slot_design):
            slot -= left @ coordinates
            accumulator.append(slot)
        for first in range(0, p, base.chunk_rows):
            base.check()
            last = min(p, first+base.chunk_rows)
            penalty_left = base.root_penalties[first:last, None] * base.right_scaled[first:last]
            accumulator.append(penalty_left @ coordinates)
        singular, right = accumulator.svd()
        # The original rectangular F has n+p rows. Do not report artificial
        # square-QR padding as extra singular values; no numerical rank trim.
        spectrum_length = min(n+p, q)
        singular, right = singular[:spectrum_length], right[:spectrum_length]
        eigenvalues = singular*singular
        denominators = eigenvalues[:, None] + np.asarray(RIDGE_GRID)[None, :]
        term = np.sum(eigenvalues[:, None] / denominators, axis=0)
        numerators = np.zeros(spectrum_length)
        leverages = {int(index): base.base_leverage.copy() for index in indices}
        for first, last, left, slot in _paired_blocks(base, slot_design):
            slot -= left @ coordinates
            projected = slot @ right.T
            projected *= projected
            numerators += np.sum(projected, axis=0)
            for index in indices:
                leverages[index][first:last] += np.sum(projected/denominators[:, index], axis=1)
        increment = np.sum(numerators[:, None]/denominators, axis=0)
        total = base.model_edf + increment
    if not all(np.isfinite(value).all() for value in (singular, term, increment, total, *leverages.values())):
        raise ArithmeticError("Exact streamed EDF/leverage is not numerically representable")
    curve = SlotCapacityCurve(slot_name, q, tuple(map(float, singular)), tuple(map(float, term)),
                             tuple(map(float, increment)), tuple(map(float, total)))
    base.check()
    return StreamedSlot(curve, MappingProxyType({key: _frozen(value) for key, value in leverages.items()}),
                        estimate["required_array_bytes"])


def streamed_slot_capacity_curves(*, base_design, slot_designs, sample_weights, base_penalties,
                                 base_rank_relative_tolerance, chunk_rows, qr_block_size,
                                 array_byte_cap, leverage_penalty_indices, budget_check):
    """Return existing SlotCapacityResult plus optional exact leverage vectors.

    All slot names, prefix joins and peak allowances are checked before the
    base factorization. All slots complete sequentially or the call raises;
    there is no partial result, empirical execution or persistence here.
    """
    if (not 1 <= len(slot_designs) <= 10 or any(not isinstance(name, str) or not name for name in slot_designs)
            or set(leverage_penalty_indices) != set(slot_designs)):
        raise ValueError("Explicit slot names and per-slot leverage requests are required")
    cap = _integer(array_byte_cap, "array byte cap")
    requests = {name: _indices(values) for name, values in leverage_penalty_indices.items()}
    count = sum(map(len, requests.values()))
    for name, slot in slot_designs.items():
        _same_rows_and_base(base_design, slot)
        estimate = estimate_array_bytes(rows=base_design.rows, base_columns=base_design.columns,
            slot_columns=slot.columns, chunk_rows=chunk_rows, qr_block_size=qr_block_size,
            retained_leverage_vectors=count)
        if estimate["required_array_bytes"] > cap:
            raise MemoryError("Complete streamed slot set exceeds the explicit array allowance")
    base = prepare_streamed_base(base_design=base_design, sample_weights=sample_weights,
        base_penalties=base_penalties, base_rank_relative_tolerance=base_rank_relative_tolerance,
        chunk_rows=chunk_rows, qr_block_size=qr_block_size, array_byte_cap=cap,
        retained_leverage_vectors=count, budget_check=budget_check)
    curves, leverage = [], {}
    for name, slot in slot_designs.items():
        result = evaluate_streamed_slot(base, slot_name=name, slot_design=slot,
            leverage_penalty_indices=requests[name])
        curves.append(result.curve)
        leverage[name] = result.joint_leverages
    budget_check()
    return SlotCapacityResult(RIDGE_GRID, base.source.columns, base.numerical_rank,
        base.singular_values, base.rank_relative_tolerance, base.rank_threshold, base.model_edf,
        tuple(curves)), MappingProxyType(leverage)
